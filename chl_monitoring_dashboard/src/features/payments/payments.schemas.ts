import { z } from 'zod'
import type { ActionStatus, Open, OverviewFilters } from '@/features/overview/overview.schemas'

const open = <T extends string>() => z.custom<Open<T>>((value) => typeof value === 'string')

/**
 * The payment methods the backend may report (SRD 10, "Payment Method
 * Details"); others it returns are shown as they come.
 */
export const PAYMENT_METHODS = [
  'qr',
  'ussd',
  'transfer',
  'generated_account',
  'pos_card',
  'chl_platform',
] as const
export type PaymentMethod = (typeof PAYMENT_METHODS)[number]

/** Payment Pending and Payment Received, as CHL reports them (SRD 10, "Payment Status"). */
export const PAYMENT_STATUSES = ['pending', 'received'] as const
export type PaymentStatus = (typeof PAYMENT_STATUSES)[number]

/** A transaction linked to a notice: its payment, and the trip activated after it. */
export const relatedTransactionSchema = z.object({
  reference: z.string(),
  kind: open<'payment' | 'trip_activation'>(),
  at: z.string(),
})

/**
 * What CHL recorded after payment (SRD 10, "Post-Payment Compliance"). Kept
 * apart from the payment status: a payment received is not a trip activated.
 */
export const complianceSchema = z.object({
  /** Whether CHL recorded a trip as activated after the payment. */
  tripActivated: z.boolean(),
  tripReference: z.string().nullable(),
  /**
   * Whether CHL started the vehicle's tagging process: "initiated" or
   * "not_initiated"; null where tagging does not apply to the violation.
   */
  tagging: open<'initiated' | 'not_initiated'>().nullable(),
  /** The compliance outcome CHL recorded, in its own words; null when none yet. */
  outcome: z.string().nullable(),
  /** When CHL last updated it; null when it has not. */
  updatedAt: z.string().nullable(),
})

/** A demand notice (invoice) generated by CHL for a violation (SRD 10). */
export const demandNoticeSchema = z.object({
  id: z.string(),
  issuedAt: z.string(),
  /** The violation the notice was generated for. */
  violation: z.object({
    id: z.string(),
    category: z.string(),
    status: open<ActionStatus>(),
  }),
  plate: z.string(),
  vehicleId: z.string().nullable(),
  vehicleType: z.string().nullable(),
  agent: z.object({ id: z.string(), name: z.string() }),
  location: z.object({ id: z.string(), name: z.string(), area: z.string(), code: z.string() }),
  verificationReference: z.string(),
  /** In naira, as CHL calculated them; each null when CHL does not supply it. */
  amounts: z.object({
    levy: z.number().nonnegative().nullable(),
    penalty: z.number().nonnegative().nullable(),
    total: z.number().nonnegative().nullable(),
  }),
  /** The reference the vehicle owner pays against; null when CHL supplies none. */
  paymentReference: z.string().nullable(),
  /** The payment method the backend reports, and its account or reference where it has one. */
  method: z.object({ type: open<PaymentMethod>(), detail: z.string().nullable() }).nullable(),
  status: open<PaymentStatus>(),
  /** When CHL confirmed payment; null while pending. */
  paidAt: z.string().nullable(),
  /** What CHL recorded after payment; null until payment is received. */
  compliance: complianceSchema.nullable(),
  /** The payment's transaction, then the trip activation's, oldest first. */
  transactions: z.array(relatedTransactionSchema),
})

export const paymentsMonitoringSchema = z.object({
  /** The latest record CHL received in scope, at any time; null when none. */
  latestReceivedAt: z.string().nullable(),
  /** The demand notices for violations in the area and period, newest first. */
  notices: z.array(demandNoticeSchema),
})

export type RelatedTransaction = z.infer<typeof relatedTransactionSchema>
export type Compliance = z.infer<typeof complianceSchema>
export type DemandNotice = z.infer<typeof demandNoticeSchema>
export type PaymentsMonitoring = z.infer<typeof paymentsMonitoringSchema>

/** The area, period, agent and organization, as on the Overview. */
export type PaymentsFilters = OverviewFilters
